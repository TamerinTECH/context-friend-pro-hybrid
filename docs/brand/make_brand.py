"""Generates every ContextFriend logo asset from one geometry.

    python -I docs/brand/make_brand.py

Writes the SVG masters and PNGs in docs/brand/ and the Android vector drawables in android/app/src/main/res/.
PNGs are rendered by headless Chrome (no extra Python packages). The logo is a redraw of the TamerinTECH
ContextFriend logo: a blue box, a yellow lid with three sound bars, two smiling eyes.
"""
import math, os, shutil, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BRAND = os.path.join(ROOT, "docs", "brand")
RES = os.path.join(ROOT, "android", "app", "src", "main", "res")
CHROME = r"C:\Program Files\Google\Chrome\Application\chrome.exe"

BLUE, YELLOW, WHITE, NAVY, SOFT = "#245FD6", "#F6C453", "#FFFFFF", "#162E51", "#EAF1FF"

# ---- geometry in a 100 x 100 logo box (content spans x 5..95, y 9..90) --------------------------------------------
LID = "M36,9 L64,9 Q70,9 71.4,15 L74.2,28 L25.8,28 L28.6,15 Q30,9 36,9 Z"
BODY = "M22,28 H78 A17,17 0 0 1 95,45 V73 A17,17 0 0 1 78,90 H22 A17,17 0 0 1 5,73 V45 A17,17 0 0 1 22,28 Z"
BARS = [(43.0, 14.5, 23.5), (50.0, 12.0, 25.0), (57.0, 15.5, 22.5)]   # centre x, top, bottom
BAR_W = 4.6
EYES = [(31.0, 59.0), (69.0, 59.0)]
EYE_R, EYE_W, EYE_FROM, EYE_TO = 10.0, 4.6, 212.0, 328.0
CENTER_X, CENTER_Y = 50.0, 49.5


def bar_path(cx, top, bottom):
    r = BAR_W / 2
    return (f"M{cx - r:.2f},{top + r:.2f} A{r},{r} 0 0 1 {cx + r:.2f},{top + r:.2f} V{bottom - r:.2f} "
            f"A{r},{r} 0 0 1 {cx - r:.2f},{bottom - r:.2f} Z")


def pt(cx, cy, r, deg):
    a = math.radians(deg)
    return cx + r * math.cos(a), cy + r * math.sin(a)


def eye_stroke(cx, cy):
    (x1, y1), (x2, y2) = pt(cx, cy, EYE_R, EYE_FROM), pt(cx, cy, EYE_R, EYE_TO)
    return f"M{x1:.2f},{y1:.2f} A{EYE_R},{EYE_R} 0 0 1 {x2:.2f},{y2:.2f}"


def eye_outline(cx, cy, steps=24):
    """The stroked eye as a filled outline (outer arc, round cap, inner arc, round cap), for one-colour icons."""
    outer, inner, half = EYE_R + EYE_W / 2, EYE_R - EYE_W / 2, EYE_W / 2
    pts = [pt(cx, cy, outer, EYE_FROM + (EYE_TO - EYE_FROM) * i / steps) for i in range(steps + 1)]
    ex, ey = pt(cx, cy, EYE_R, EYE_TO)
    pts += [pt(ex, ey, half, EYE_TO + 180 * i / 12) for i in range(1, 12)]
    pts += [pt(cx, cy, inner, EYE_TO - (EYE_TO - EYE_FROM) * i / steps) for i in range(steps + 1)]
    sx, sy = pt(cx, cy, EYE_R, EYE_FROM)
    pts += [pt(sx, sy, half, EYE_FROM + 180 + 180 * i / 12) for i in range(1, 12)]
    return "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + " Z"


SILHOUETTE = " ".join([LID] + [bar_path(*b) for b in BARS] + [BODY] + [eye_outline(*e) for e in EYES])


# ---- SVG ----------------------------------------------------------------------------------------------------------
def svg_logo_group(scale, tx, ty):
    bars = "".join(f'<path d="{bar_path(*b)}" fill="{BLUE}"/>' for b in BARS)
    eyes = "".join(f'<path d="{eye_stroke(*e)}" fill="none" stroke="{WHITE}" stroke-width="{EYE_W}" stroke-linecap="round"/>' for e in EYES)
    return (f'<g transform="translate({tx:.2f} {ty:.2f}) scale({scale:.4f})">'
            f'<path d="{LID}" fill="{YELLOW}"/>{bars}<path d="{BODY}" fill="{BLUE}"/>{eyes}</g>')


def centered(size_w, size_h, scale, cx=None, cy=None):
    cx = size_w / 2 if cx is None else cx
    cy = size_h / 2 if cy is None else cy
    return svg_logo_group(scale, cx - CENTER_X * scale, cy - CENTER_Y * scale)


def svg(w, h, body, background=None):
    bg = f'<rect width="{w}" height="{h}" fill="{background}"/>' if background else ""
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">{bg}{body}</svg>\n'


FONT = "font-family=\"'Segoe UI', Roboto, Arial, sans-serif\""


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def render(svg_path, png_path, w, h):
    profile = tempfile.mkdtemp(prefix="cf-brand-")
    try:
        subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars", f"--user-data-dir={profile}",
                        "--default-background-color=00000000", f"--window-size={w},{h}", f"--screenshot={png_path}",
                        "file:///" + svg_path.replace("\\", "/")], check=True, capture_output=True, timeout=60)
    finally:
        shutil.rmtree(profile, ignore_errors=True)


# ---- Android vector drawables -------------------------------------------------------------------------------------
def vd(width_dp, height_dp, vw, vh, inner, comment):
    return (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {comment} Generated by docs/brand/make_brand.py. -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="{width_dp}dp" android:height="{height_dp}dp" '
            f'android:viewportWidth="{vw}" android:viewportHeight="{vh}">\n{inner}</vector>\n')


def vd_group(scale, tx, ty, paths):
    return f'    <group android:translateX="{tx:.2f}" android:translateY="{ty:.2f}" android:scaleX="{scale}" android:scaleY="{scale}">\n{paths}    </group>\n'


def vd_color_paths():
    bars = "".join(f'        <path android:fillColor="{BLUE}" android:pathData="{bar_path(*b)}" />\n' for b in BARS)
    eyes = "".join(f'        <path android:strokeColor="{WHITE}" android:strokeWidth="{EYE_W}" android:strokeLineCap="round" android:pathData="{eye_stroke(*e)}" />\n' for e in EYES)
    return (f'        <path android:fillColor="{YELLOW}" android:pathData="{LID}" />\n{bars}'
            f'        <path android:fillColor="{BLUE}" android:pathData="{BODY}" />\n{eyes}')


def vd_silhouette(color):
    return f'        <path android:fillColor="{color}" android:fillType="evenOdd" android:pathData="{SILHOUETTE}" />\n'


def main():
    # SVG masters
    logo_svg = os.path.join(BRAND, "contextfriend-logo.svg")
    write(logo_svg, svg(512, 512, centered(512, 512, 5.0)))
    write(os.path.join(BRAND, "contextfriend-logo-mono.svg"),
          svg(512, 512, f'<g transform="translate({256 - CENTER_X * 5:.2f} {256 - CENTER_Y * 5:.2f}) scale(5)"><path d="{SILHOUETTE}" fill="{NAVY}" fill-rule="evenodd"/></g>'))
    icon_svg = os.path.join(BRAND, "contextfriend-app-icon.svg")
    write(icon_svg, svg(512, 512, centered(512, 512, 3.9), background=WHITE))
    thumb_svg = os.path.join(BRAND, "devpost-thumbnail.svg")
    write(thumb_svg, svg(1200, 800,
        centered(1200, 800, 4.6, cy=300) +
        f'<text x="600" y="590" text-anchor="middle" {FONT} font-size="76" font-weight="700" fill="{NAVY}">ContextFriend Pro</text>'
        f'<text x="600" y="665" text-anchor="middle" {FONT} font-size="36" fill="#5F6E83">Meeting notes on your phone. The cloud only when you ask.</text>',
        background="#F7F8FA"))
    feature_svg = os.path.join(BRAND, "play-feature-graphic.svg")
    write(feature_svg, svg(1024, 500,
        centered(1024, 500, 3.3, cx=230, cy=250) +
        f'<text x="430" y="235" {FONT} font-size="64" font-weight="700" fill="#FFFFFF">ContextFriend Pro</text>'
        f'<text x="432" y="300" {FONT} font-size="30" fill="#CDDAEF">Record. Get notes on this phone.</text>'
        f'<text x="432" y="342" {FONT} font-size="30" fill="#CDDAEF">Share only what you choose.</text>',
        background=NAVY))

    # PNGs
    png = os.path.join(BRAND, "png")
    os.makedirs(png, exist_ok=True)
    for size in (1024, 512, 192, 96, 48):
        sized = os.path.join(png, f"_logo-{size}.svg")
        write(sized, svg(size, size, centered(size, size, 5.0 * size / 512)))
        render(sized, os.path.join(png, f"contextfriend-logo-{size}.png"), size, size)
        os.remove(sized)
    render(icon_svg, os.path.join(png, "play-icon-512.png"), 512, 512)
    render(thumb_svg, os.path.join(png, "devpost-thumbnail-1200x800.png"), 1200, 800)
    render(feature_svg, os.path.join(png, "play-feature-graphic-1024x500.png"), 1024, 500)

    # Android: adaptive icon (108 dp canvas, 66 dp safe zone), themed monochrome, notification, in-app logo
    s = 0.6
    write(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"),
          vd(108, 108, 108, 108, vd_group(s, 54 - CENTER_X * s, 54 - CENTER_Y * s, vd_color_paths()), "ContextFriend logo inside the adaptive icon safe zone."))
    write(os.path.join(RES, "drawable", "ic_launcher_monochrome.xml"),
          vd(108, 108, 108, 108, vd_group(s, 54 - CENTER_X * s, 54 - CENTER_Y * s, vd_silhouette("#FF000000")), "One-colour logo for Android themed icons."))
    n = 0.24
    write(os.path.join(RES, "drawable", "ic_stat_contextfriend.xml"),
          vd(24, 24, 24, 24, vd_group(n, 12 - CENTER_X * n, 12 - CENTER_Y * n, vd_silhouette("#FFFFFFFF")), "Notification icon: white silhouette."))
    write(os.path.join(RES, "drawable", "logo.xml"),
          vd(100, 100, 100, 100, vd_group(1.0, 0, 50 - CENTER_Y, vd_color_paths()), "Full-colour logo for in-app use."))
    adaptive = ('<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                '    <background android:drawable="@color/ic_launcher_background" />\n'
                '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
                '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n</adaptive-icon>\n')
    write(os.path.join(RES, "mipmap-anydpi-v26", "ic_launcher.xml"), adaptive)
    write(os.path.join(RES, "mipmap-anydpi-v26", "ic_launcher_round.xml"), adaptive)
    write(os.path.join(RES, "values", "colors.xml"), '<resources><color name="ic_launcher_background">#FFFFFF</color></resources>\n')
    print("brand assets written")


if __name__ == "__main__":
    sys.exit(main())
